//! ⚠️ 这里**不要** `mod` 主程序现有的那些模块（`agent` / `service` / `ui` …）：
//! 那会让它们被编译两份（lib + bin），重复的静态初始化与符号会带来难以察觉的漂移。
//! 本 lib 只暴露真正需要跨目标复用的东西。

